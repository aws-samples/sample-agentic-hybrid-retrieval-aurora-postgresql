\set ON_ERROR_STOP on

CREATE TABLE IF NOT EXISTS mosaic_bench.profile (
    profile_key             text PRIMARY KEY,
    description             text NOT NULL,
    vector_count            bigint NOT NULL CHECK (vector_count > 0),
    dimensions              integer NOT NULL CHECK (dimensions > 0),
    distance_metric         text NOT NULL DEFAULT 'cosine',
    hnsw_m                  integer NOT NULL DEFAULT 16,
    hnsw_ef_construction    integer NOT NULL DEFAULT 200,
    hnsw_ef_search          integer NOT NULL DEFAULT 100,
    iterative_scan          text NOT NULL DEFAULT 'relaxed_order',
    max_scan_tuples         integer NOT NULL DEFAULT 20000,
    scan_mem_multiplier     real NOT NULL DEFAULT 1,
    filter_selectivity      real CHECK (filter_selectivity BETWEEN 0 AND 1),
    result_kind             mosaic.benchmark_result_kind NOT NULL,
    environment_label       text,
    metadata                jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE IF NOT EXISTS mosaic_bench.run (
    benchmark_run_id        uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    profile_key             text NOT NULL REFERENCES mosaic_bench.profile(profile_key),
    run_label               text NOT NULL,
    database_instance_id    text,
    database_version        text,
    vector_extension_version text,
    instance_class          text,
    dataset_manifest        text,
    source_revision         text,
    source_worktree_dirty   boolean,
    dataset_manifest_sha256 text,
    index_size_bytes        bigint CHECK (index_size_bytes >= 0),
    started_at              timestamptz NOT NULL DEFAULT now(),
    completed_at            timestamptz,
    notes                   text,
    metadata                jsonb NOT NULL DEFAULT '{}'::jsonb
);

ALTER TABLE mosaic_bench.run
    ADD COLUMN IF NOT EXISTS database_instance_id text,
    ADD COLUMN IF NOT EXISTS source_revision text,
    ADD COLUMN IF NOT EXISTS source_worktree_dirty boolean,
    ADD COLUMN IF NOT EXISTS dataset_manifest_sha256 text,
    ADD COLUMN IF NOT EXISTS index_size_bytes bigint;

ALTER TABLE mosaic_bench.run
    DROP CONSTRAINT IF EXISTS benchmark_run_dataset_manifest_sha256_check;
ALTER TABLE mosaic_bench.run
    ADD CONSTRAINT benchmark_run_dataset_manifest_sha256_check
    CHECK (
        dataset_manifest_sha256 IS NULL
        OR dataset_manifest_sha256 ~ '^[0-9a-f]{64}$'
    );

ALTER TABLE mosaic_bench.run
    DROP CONSTRAINT IF EXISTS benchmark_run_index_size_bytes_check;
ALTER TABLE mosaic_bench.run
    ADD CONSTRAINT benchmark_run_index_size_bytes_check
    CHECK (index_size_bytes IS NULL OR index_size_bytes >= 0);

CREATE TABLE IF NOT EXISTS mosaic_bench.measurement (
    measurement_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    benchmark_run_id     uuid NOT NULL REFERENCES mosaic_bench.run(benchmark_run_id) ON DELETE CASCADE,
    measurement_name     text NOT NULL,
    measurement_value    double precision NOT NULL,
    unit                 text NOT NULL,
    percentile           numeric(5,2),
    query_id             text,
    filter_profile       jsonb NOT NULL DEFAULT '{}'::jsonb,
    plan_json            jsonb,
    captured_at          timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS mosaic_bench.vector_item (
    item_id          bigint PRIMARY KEY,
    cluster_id       integer NOT NULL,
    domain_id        smallint NOT NULL,
    category_id      integer NOT NULL,
    price_bucket     smallint NOT NULL,
    embedding        vector(1024) NOT NULL,
    metadata         jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS bench_vector_item_filter_idx
    ON mosaic_bench.vector_item (domain_id, category_id, price_bucket);
CREATE INDEX IF NOT EXISTS bench_run_profile_idx
    ON mosaic_bench.run (profile_key, started_at DESC);
CREATE INDEX IF NOT EXISTS bench_measurement_run_name_idx
    ON mosaic_bench.measurement (benchmark_run_id, measurement_name, percentile);
